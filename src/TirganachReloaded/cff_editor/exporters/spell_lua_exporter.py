class SpellLuaExporter:
    """Exports spell data to Lua scripts for SpellForce"""

    def __init__(self, output_dir: str = "exported_spells"):
        self.output_dir = output_dir
        self.ensure_output_dir()

    def ensure_output_dir(self):
        """Create output directory if it doesn't exist"""
        os.makedirs(self.output_dir, exist_ok=True)

    def export_spell(self, spell_data: SpellCreationData) -> Dict[str, str]:
        """
        Export spell to Lua files

        Returns:
            Dict mapping file paths to Lua code content
        """
        files = {}

        # 1. sql_spellline.lua entry
        files["script/sql_spellline.lua"] = self.generate_spellline_entry(spell_data)

        # 2. Visual effects script
        vfx_filename = f"object/object_effect_{spell_data.internal_name.lower()}.lua"
        files[vfx_filename] = self.generate_vfx_script(spell_data)

        # 3. Sound event registration
        files["script/DrwSound.lua"] = self.generate_sound_entry(spell_data)

        # 4. Spell stats data (for CFF integration)
        stats_filename = f"data/spell_stats_{spell_data.internal_name.lower()}.lua"
        files[stats_filename] = self.generate_spell_stats(spell_data)

        return files

    def generate_spellline_entry(self, spell_data: SpellCreationData) -> str:
        """Generate sql_spellline.lua entry"""

        # Map magic school to spell line base
        school_base_map = {
            "WHITE": 0,
            "FIRE": 1,
            "ICE": 2,
            "BLACK": 3,
            "MENTAL": 4,
            "EARTH": 5
        }
        spell_line_base = school_base_map.get(spell_data.magic_school.name, 0)

        lua_code = f"""-- Custom Spell: {spell_data.spell_name}
-- Generated by SpellForce Spell Wizard
-- Date: {spell_data.created_date}
-- Author: {spell_data.author}

[{spell_data.spell_line_id}] = {{
    includename="{spell_data.internal_name}",
    player=1,  -- Player can cast
    npc=0,     -- NPC cannot cast (custom spell)
    flag3=0,   -- Not an aura
    flag4=0,   -- Not a toggle
    flag5=1,
    flag6=0,
    flag7=0,
    flag8=0,
    effectscast={{"{spell_data.vfx_cast}"}},
    effectsresolve={{"{spell_data.vfx_resolve}"}},
    effectsprojectile={{"{spell_data.vfx_projectile}"}},
    effectstarget={{"{spell_data.vfx_target}"}},
    effectsovertime={{"{spell_data.vfx_overtime}"}},
    spelllinebase={spell_line_base},
}}

"""
        return lua_code

    def generate_vfx_script(self, spell_data: SpellCreationData) -> str:
        """Generate visual effects Lua script"""

        lua_code = f"""-- Visual Effects for {spell_data.spell_name}
-- Auto-generated by Spell Wizard
-- Date: {spell_data.created_date}

"""

        # Cast Effect
        if spell_data.vfx_cast:
            lua_code += self.get_vfx_template(spell_data.vfx_cast, "cast")
            lua_code += f'EffectSave("{spell_data.vfx_cast}")\n\n'

        # Projectile Effect
        if spell_data.vfx_projectile and spell_data.has_projectile:
            lua_code += self.get_vfx_template(spell_data.vfx_projectile, "projectile")
            lua_code += f'EffectSave("{spell_data.vfx_projectile}")\n\n'

        # Resolve Effect
        if spell_data.vfx_resolve:
            lua_code += self.get_vfx_template(spell_data.vfx_resolve, "resolve")
            lua_code += f'EffectSave("{spell_data.vfx_resolve}")\n\n'

        # Target Effect
        if spell_data.vfx_target:
            lua_code += self.get_vfx_template(spell_data.vfx_target, "target")
            lua_code += f'EffectSave("{spell_data.vfx_target}")\n\n'

        # Overtime Effect (for buffs/debuffs)
        if spell_data.vfx_overtime:
            lua_code += self.get_vfx_template(spell_data.vfx_overtime, "overtime")
            lua_code += f'EffectSave("{spell_data.vfx_overtime}")\n\n'

        return lua_code

