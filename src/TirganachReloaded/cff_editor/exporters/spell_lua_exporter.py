class SpellValidator:
    """Validates spell data before export"""

    def __init__(self):
        self.errors = []
        self.warnings = []

    def validate(self, spell_data: SpellCreationData) -> tuple[List[str], List[str]]:
        """Validate spell data and return errors/warnings"""
        self.errors = []
        self.warnings = []

        # Check spell name
        if not spell_data.spell_name.strip():
            self.errors.append("Spell name is required")

        # Check internal name
        if not spell_data.internal_name.strip():
            self.errors.append("Internal name is required")
        elif " " in spell_data.internal_name:
            self.errors.append("Internal name cannot contain spaces")

        # Check level progression
        if len(spell_data.levels) != spell_data.num_levels:
            self.errors.append(f"Level count mismatch: expected {spell_data.num_levels}, got {len(spell_data.levels)}")

        # Validate level data
        for i, level in enumerate(spell_data.levels):
            if level.damage_min > level.damage_max:
                self.errors.append(f"Level {i+1}: Min damage ({level.damage_min}) > Max damage ({level.damage_max})")

            if level.mana_cost < 0:
                self.errors.append(f"Level {i+1}: Mana cost cannot be negative")

            if level.cooldown < 0:
                self.errors.append(f"Level {i+1}: Cooldown cannot be negative")

            if level.cast_time < 0:
                self.errors.append(f"Level {i+1}: Cast time cannot be negative")

            # Warnings for potentially unbalanced spells
            if level.mana_cost == 0 and (level.damage_min > 0 or level.damage_max > 0):
                self.warnings.append(f"Level {i+1}: Free spell with damage - potential balance issue")

            if level.damage_max > 1000:
                self.warnings.append(f"Level {i+1}: Very high damage ({level.damage_max})")

            # Check scaling consistency
            if i > 0:
                prev_level = spell_data.levels[i - 1]
                if level.damage_max <= prev_level.damage_max and level.damage_max > 0:
                    self.warnings.append(f"Level {i+1}: Damage not increasing from previous level")

        # Check spell line ID uniqueness (simplified check)
        if spell_data.spell_line_id < 300 or spell_data.spell_line_id > 999:
            self.errors.append("Spell Line ID must be between 300-999 for custom spells")

        # Check VFX references (simplified)
        vfx_effects = [spell_data.vfx_cast, spell_data.vfx_projectile,
                      spell_data.vfx_resolve, spell_data.vfx_target, spell_data.vfx_overtime]
        for vfx in vfx_effects:
            if vfx and vfx.startswith("Custom"):
                self.warnings.append(f"VFX '{vfx}' is marked as custom - ensure it exists in game files")

        return self.errors, self.warnings

    def get_balance_score(self, spell_data: SpellCreationData) -> Dict[str, Any]:
        """Calculate balance score for the spell"""
        if not spell_data.levels:
            return {"score": 0, "category": "Unknown", "issues": ["No level data"]}

        # Use highest level for balance calculation
        max_level = spell_data.levels[-1]

        # Calculate damage per mana (DPM)
        avg_damage = (max_level.damage_min + max_level.damage_max) / 2
        dpm = avg_damage / max_level.mana_cost if max_level.mana_cost > 0 else 0

        # Calculate damage per second
        effective_time = max_level.cast_time + max_level.cooldown
        dps = avg_damage / effective_time if effective_time > 0 else 0

        # Power rating (arbitrary scale)
        power_rating = (dpm * 10 + dps * 5) / 2

        # Categorize
        if power_rating < 20:
            category = "Weak"
        elif power_rating < 40:
            category = "Balanced"
        elif power_rating < 60:
            category = "Strong"
        else:
            category = "Overpowered"

        return {
            "damage_per_mana": round(dpm, 2),
            "damage_per_second": round(dps, 2),
            "power_rating": round(power_rating, 1),
            "balance_category": category,
        }


